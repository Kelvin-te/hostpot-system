    /**
     * Configure the router's hotspot server profile to serve the local hotspot
     * files (login.html, status.html, etc.) instead of redirecting to an external
     * captive portal. Ensures http-login-page is cleared so RouterOS uses the
     * local HTML directory, and adds the Laravel app + Google Fonts to the
     * walled garden so the local page can call the API at runtime.
     */
    public function configureLocalPortal(Router $router, string $apiBaseUrl): array
    {
        try {
            $client = $this->connectToRouter($router);

            if (!$client) {
                return ['success' => false, 'message' => 'Cannot connect to router'];
            }

            $profileQuery = new Query('/ip/hotspot/profile/print');
            $profiles = $client->query($profileQuery)->read();

            foreach ($profiles as $profile) {
                if (isset($profile['.id'])) {
                    $setQuery = new Query('/ip/hotspot/profile/set');
                    $setQuery->equal('.id', $profile['.id']);
                    // Use both CHAP and PAP so login.html can do either path,
                    // plus mac-cookie for seamless reconnects.
                    $setQuery->equal('login-by', 'http-pap,http-chap,mac-cookie');
                    // Serve the local login.html from the hotspot html directory.
                    $setQuery->equal('html-directory', 'hotspot');
                    $setQuery->equal('split-user-domain', 'no');
                    // Force local user authentication; disable any legacy RADIUS config.
                    $setQuery->equal('use-radius', 'no');
                    $setQuery->equal('radius-accounting', 'no');
                    $client->query($setQuery)->read();
                }
            }

            $apiHost = parse_url($apiBaseUrl, PHP_URL_HOST);
            $walledGardenHosts = array_filter([
                $apiHost,
                'fonts.googleapis.com',
                'fonts.gstatic.com',
                'connectivitycheck.gstatic.com',
                'captive.apple.com',
                'www.msftconnecttest.com',
                'detectportal.firefox.com',
            ]);

            foreach ($walledGardenHosts as $host) {
                if (!$host) {
                    continue;
                }
                $existingQuery = new Query('/ip/hotspot/walled-garden/print');
                $existingQuery->where('dst-host', $host);
                $existingEntries = $client->query($existingQuery)->read();

                if (empty($existingEntries)) {
                    $addGardenQuery = new Query('/ip/hotspot/walled-garden/add');
                    $addGardenQuery->equal('dst-host', $host);
                    $response = $client->query($addGardenQuery)->read();

                    if ($this->responseHasError($response)) {
                        throw new Exception("Router rejected walled garden host {$host}: " . $this->responseErrorMessage($response));
                    }
                }
            }

            Log::info('Local portal configured on router', [
                'router_id' => $router->id,
                'api_base_url' => $apiBaseUrl,
            ]);

            return ['success' => true, 'message' => 'Router configured to use local hotspot files'];

        } catch (Exception $e) {
            Log::error('Failed to configure external portal', [
                'router_id' => $router->id,
                'error' => $e->getMessage(),
            ]);

            return ['success' => false, 'message' => 'Portal configuration failed: ' . $e->getMessage()];
        }
    }

    /**
     * One-click hotspot setup for a router.
     *
     * Creates/updates a local hotspot user profile, ensures a HotSpot server
     * is running on the configured interface, and applies the local portal
     * configuration + walled garden entries.
     */
    public function setupHotspot(Router $router): array
    {
        try {
            $client = $this->connectToRouter($router);

            if (!$client) {
                return ['success' => false, 'message' => 'Cannot connect to router'];
            }

            $interface = $router->hotspot_interface;

            if (!$interface) {
                return [
                    'success' => false,
                    'message' => 'No hotspot interface configured. Sync HotSpot Gateway IP first.',
                ];
            }

            $serverProfileName = 'hotspot-local';

            // Ensure the hotspot SERVER profile exists and uses local authentication.
            // This is NOT a user profile; it controls login methods, RADIUS, and the portal page.
            $serverProfileQuery = (new Query('/ip/hotspot/profile/print'))
                ->where('name', $serverProfileName);
            $serverProfiles = $client->query($serverProfileQuery)->read();

            $serverProfileData = [
                'login-by' => 'http-pap,http-chap,mac-cookie',
                'html-directory' => 'hotspot',
                'split-user-domain' => 'no',
                'use-radius' => 'no',
                'radius-accounting' => 'no',
            ];

            if (empty($serverProfiles)) {
                $addServerProfile = new Query('/ip/hotspot/profile/add');
                $addServerProfile->equal('name', $serverProfileName);
                foreach ($serverProfileData as $key => $value) {
                    $addServerProfile->equal($key, $value);
                }
                $client->query($addServerProfile)->read();
                Log::info('Created hotspot server profile', ['router_id' => $router->id, 'profile' => $serverProfileName]);
            } else {
                $setServerProfile = new Query('/ip/hotspot/profile/set');
                $setServerProfile->equal('.id', $serverProfiles[0]['.id']);
                foreach ($serverProfileData as $key => $value) {
                    $setServerProfile->equal($key, $value);
                }
                $client->query($setServerProfile)->read();
