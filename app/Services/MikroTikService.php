    /**
     * Create or update user profile for the package associated with a session.
     */
    protected function createOrUpdateUserProfile(Client $client, HotspotSession $session): string
    {
        return $this->syncPackageProfile($client, $session->package);
    }

    /**
     * Create or update a hotspot user profile for a package on the router.
     */
    protected function syncPackageProfile(Client $client, Package $package): string
    {
        $profileName = 'pkg_' . $package->id . '_' . str_replace(' ', '_', strtolower($package->name));

        try {
            $query = (new Query('/ip/hotspot/user/profile/print'))
                ->where('name', $profileName);

            $existingProfiles = $client->query($query)->read();

            if (empty($existingProfiles)) {
                $this->createUserProfile($client, $profileName, $package);
            } else {
                $this->updateUserProfile($client, $profileName, $package, $existingProfiles[0]['.id']);
            }

            return $profileName;
        } catch (Exception $e) {
            Log::error('Failed to create/update user profile', [
                'profile_name' => $profileName,
                'package_id' => $package->id,
                'error' => $e->getMessage(),
            ]);

            throw $e;
        }
    }

    /**
     * Create user profile
     */
    protected function createUserProfile(Client $client, string $profileName, $package): void
    {
        $profileData = [
            'name' => $profileName,
            'session-timeout' => $this->formatSessionTimeout($package),
            'idle-timeout' => $this->formatSessionTimeout($package),
            'keepalive-timeout' => '00:02:00',
            'status-autorefresh' => '00:01:00',
        ];

        $rateLimit = $this->formatRateLimit($package);
        if ($rateLimit) {
            $profileData['rate-limit'] = $rateLimit;
        }

        Log::info('Creating hotspot user profile on router', [
            'profile_name' => $profileName,
            'package_id' => $package->id,
            'rate_limit' => $rateLimit,
        ]);

        $sharedUsers = $this->formatSharedUsers($package->shared_users ?? null);
        if ($sharedUsers) {
            $profileData['shared-users'] = $sharedUsers;
        }

        $query = new Query('/ip/hotspot/user/profile/add');
        foreach ($profileData as $key => $value) {
            $query->equal($key, $value);
        }

        $addResponse = $client->query($query)->read();

        // Check for !trap error in the response (RouterOS returns traps without throwing)
        if (isset($addResponse['after']['message'])) {
            throw new Exception("Router rejected profile {$profileName}: " . $addResponse['after']['message']);
        }

        // Verify the profile actually exists on the router
        $verifyQuery = (new Query('/ip/hotspot/user/profile/print'))->where('name', $profileName);
        $verify = $client->query($verifyQuery)->read();

        if (empty($verify)) {
            throw new Exception("Profile creation failed: profile {$profileName} was not found after creation.");
        }

        Log::info('Created hotspot user profile', [
            'profile_name' => $profileName,
            'package_id' => $package->id,
            'profile_id' => $verify[0]['.id'] ?? null,
        ]);
    }

    /**
     * Update existing user profile
     */
    protected function updateUserProfile(Client $client, string $profileName, $package, string $profileId): void
    {
        $profileData = [
            'session-timeout' => $this->formatSessionTimeout($package),
            'idle-timeout' => $this->formatSessionTimeout($package),
        ];

        $rateLimit = $this->formatRateLimit($package);
        if ($rateLimit) {
            $profileData['rate-limit'] = $rateLimit;
        }

        $sharedUsers = $this->formatSharedUsers($package->shared_users ?? null);
        if ($sharedUsers) {
            $profileData['shared-users'] = $sharedUsers;
        }

        $query = new Query('/ip/hotspot/user/profile/set');
        $query->equal('.id', $profileId);

        foreach ($profileData as $key => $value) {
            $query->equal($key, $value);
        }

        $updateResponse = $client->query($query)->read();

        if (isset($updateResponse['after']['message'])) {
            throw new Exception("Router rejected profile update {$profileName}: " . $updateResponse['after']['message']);
        }

        Log::info('Updated hotspot user profile', [
            'profile_name' => $profileName,
            'package_id' => $package->id
        ]);
    }

    /**
     * Delete a package's hotspot user profile and any hotspot users tied to it
     * from the router. This should only be called when the package has no
     * active sessions in the app, so we do not disconnect online users.
     */
    public function deletePackageProfile(Router $router, Package $package): array
    {
        $profileName = 'pkg_' . $package->id . '_' . str_replace(' ', '_', strtolower($package->name));

        try {
            $client = $this->connectToRouter($router);

            if (!$client) {
                return [
                    'success' => false,
                    'message' => 'Could not connect to router',
                ];
            }

            // Remove hotspot users assigned to this profile
            $userQuery = (new Query('/ip/hotspot/user/print'))->where('profile', $profileName);
            $users = $client->query($userQuery)->read();
            $removedUsers = 0;

            foreach ($users as $user) {
                if (isset($user['.id'])) {
                    $removeQuery = (new Query('/ip/hotspot/user/remove'))->equal('.id', $user['.id']);
                    $client->query($removeQuery)->read();
                    $removedUsers++;
                }
            }

            // Remove the profile itself
            $profileQuery = (new Query('/ip/hotspot/user/profile/print'))->where('name', $profileName);
            $profiles = $client->query($profileQuery)->read();
            $removedProfiles = 0;

            foreach ($profiles as $profile) {
                if (isset($profile['.id'])) {
                    $removeQuery = (new Query('/ip/hotspot/user/profile/remove'))->equal('.id', $profile['.id']);
                    $client->query($removeQuery)->read();
                    $removedProfiles++;
                }
            }

            Log::info('Deleted package profile from router', [
                'router_id' => $router->id,
                'package_id' => $package->id,
                'profile_name' => $profileName,
                'removed_users' => $removedUsers,
                'removed_profiles' => $removedProfiles,
            ]);

            return [
                'success' => true,
                'message' => "Removed {$removedProfiles} profile and {$removedUsers} user(s) from router.",
                'removed_users' => $removedUsers,
                'removed_profiles' => $removedProfiles,
            ];
        } catch (Exception $e) {
            Log::error('Failed to delete package profile from router', [
                'router_id' => $router->id,
                'package_id' => $package->id,
                'profile_name' => $profileName,
                'error' => $e->getMessage(),
            ]);

            return [
                'success' => false,
                'message' => 'Failed to delete package profile: ' . $e->getMessage(),
            ];
        }
    }

    /**
     * Create user on MikroTik
     */
    protected function createUser(Client $client, string $username, string $password, string $profileName, HotspotSession $session): void
    {
        // Remove existing user with same name (idempotent for reactivation/retry)
        $findQuery = (new Query('/ip/hotspot/user/print'))
            ->where('name', $username);
        $existing = $client->query($findQuery)->read();

        foreach ($existing as $user) {
            if (isset($user['.id'])) {
                $removeQuery = (new Query('/ip/hotspot/user/remove'))
                    ->equal('.id', $user['.id']);
                $client->query($removeQuery)->read();
            }
        }

        $expirationComment = $session->expires_at
            ? 'exp=' . $session->expires_at->format('M/d/Y H:i:s')
            : 'exp=none';

        if (!$session->expires_at || $session->expires_at <= now()) {
            Log::error('Creating hotspot user with expired session', [
                'session_id' => $session->session_id,
                'username' => $username,
                'expires_at' => $session->expires_at?->toIso8601String(),
                'created_at' => $session->created_at?->toDateTimeString(),
            ]);
        }

        $userData = [
            'name' => $username,
            'password' => $password,
            'profile' => $profileName,
            'comment' => $expirationComment,
        ];

        // Set limit-uptime (user-level usage limit) from package validity
        $limitUptime = $this->formatLimitUptime($session->package);
        if ($limitUptime) {
            $userData['limit-uptime'] = $limitUptime;
        }

        // Add MAC address binding if available
        if ($session->mac_address) {
            $userData['mac-address'] = $session->mac_address;
        }

        $query = new Query('/ip/hotspot/user/add');
        foreach ($userData as $key => $value) {
            $query->equal($key, $value);
        }

        $addResponse = $client->query($query)->read();

        // Check for !trap error in the response (RouterOS returns traps without throwing)
        if (isset($addResponse['after']['message'])) {
            throw new Exception("Router rejected user {$username}: " . $addResponse['after']['message']);
        }

        // Verify the user actually exists on the router
        $verifyQuery = (new Query('/ip/hotspot/user/print'))->where('name', $username);
        $verify = $client->query($verifyQuery)->read();

        if (empty($verify)) {
            throw new Exception("User creation failed: user {$username} was not found after creation.");
        }

        Log::info('Created hotspot user', [
            'username' => $username,
            'profile' => $profileName,
            'session_id' => $session->session_id,
            'limit_uptime' => $limitUptime ?: 'none',
            'expiration' => $session->expires_at?->toIso8601String(),
            'user_id' => $verify[0]['.id'] ?? null,
        ]);
    }

    /**
     * Remove active sessions from MikroTik
     */
    protected function removeActiveSessions(Client $client, HotspotSession $session): void
    {
        try {
            $username = $session->mikrotik_username ?: $session->username ?: $session->session_id;

            // Filter by username in the API query — avoids fetching all active sessions
            $query = (new Query('/ip/hotspot/active/print'))
                ->where('user', $username);
            $activeSessions = $client->query($query)->read();

            foreach ($activeSessions as $activeSession) {
                // Double-check match to avoid removing wrong user
                if ($this->isMatchingSession($activeSession, $session)) {
                    $removeQuery = (new Query('/ip/hotspot/active/remove'))
                        ->equal('.id', $activeSession['.id']);

                    $client->query($removeQuery)->read();

                    Log::info('Removed active hotspot session', [
                        'session_id' => $session->session_id,
                        'mikrotik_id' => $activeSession['.id']
                    ]);
                }
            }
            
        } catch (Exception $e) {
            Log::error('Failed to remove active sessions', [
                'session_id' => $session->session_id,
                'error' => $e->getMessage()
            ]);
        }
    }

    /**
     * Remove MAC cookies for a specific session's MAC address.
     * Only removes cookies matching this user's MAC — never removes all cookies.
     */
    protected function removeHotspotCookie(Client $client, HotspotSession $session): void
    {
        if (!$session->mac_address) {
            return;
        }

        try {
            $mac = strtolower($session->mac_address);

            $query = new Query('/ip/hotspot/cookie/print');
            $cookies = $client->query($query)->read();

            foreach ($cookies as $cookie) {
                $cookieMac = strtolower($cookie['mac-address'] ?? '');
                if ($cookieMac === $mac && isset($cookie['.id'])) {
                    $removeQuery = (new Query('/ip/hotspot/cookie/remove'))
                        ->equal('.id', $cookie['.id']);
                    $client->query($removeQuery)->read();

                    Log::info('Removed hotspot cookie for MAC', [
                        'session_id' => $session->session_id,
                        'mac_address' => $mac,
                    ]);
                }
            }
        } catch (Exception $e) {
            Log::warning('Failed to remove hotspot cookie', [
                'session_id' => $session->session_id,
                'mac_address' => $session->mac_address,
                'error' => $e->getMessage(),
            ]);
        }
    }

    /**
     * Remove user from MikroTik
     */
    protected function removeUser(Client $client, HotspotSession $session): void
    {
        try {
            $username = $session->mikrotik_username ?: $session->username ?: $session->session_id;
            
            $query = (new Query('/ip/hotspot/user/print'))
                ->where('name', $username);
            
            $users = $client->query($query)->read();
            
            foreach ($users as $user) {
                $removeQuery = (new Query('/ip/hotspot/user/remove'))
                    ->equal('.id', $user['.id']);
                
                $client->query($removeQuery)->read();
                
                Log::info('Removed hotspot user', [
                    'username' => $username,
                    'session_id' => $session->session_id
                ]);
            }
            
        } catch (Exception $e) {
            Log::error('Failed to remove hotspot user', [
                'session_id' => $session->session_id,
                'error' => $e->getMessage()
            ]);
        }
    }

    /**
     * Check if MikroTik session matches our session
     */
    protected function isMatchingSession(array $activeSession, HotspotSession $session): bool
    {
        // Match by username
        $username = $session->mikrotik_username ?: $session->username ?: $session->session_id;
        if (isset($activeSession['user']) && $activeSession['user'] === $username) {
            return true;
        }

        // Match by MAC address
        if ($session->mac_address && isset($activeSession['mac-address'])) {
            if (strtolower($session->mac_address) === strtolower($activeSession['mac-address'])) {
                return true;
            }
        }

        // Match by IP address
        if ($session->ip_address && isset($activeSession['address'])) {
            if ($session->ip_address === $activeSession['address']) {
                return true;
            }
        }

        return false;
    }

    /**
     * Format shared-users for MikroTik profile.
     * 0 or null = unlimited, 1 = omit (MikroTik default), >1 = explicit value.
     */
    protected function formatSharedUsers(?int $sharedUsers): string
    {
        if ($sharedUsers === null || $sharedUsers === 0) {
            return 'unlimited';
        }

        if ($sharedUsers === 1) {
            return ''; // MikroTik default is 1, no need to set explicitly
        }

        return (string) $sharedUsers;
    }

    /**
     * Parse MikroTik uptime string to seconds.
     * Handles formats: "1d2h3m4s", "1w2d3h4m5s", "37:59:59", "1:02:03:04"
     */
    protected function parseUptimeToSeconds(string $uptime): int
    {
        // Colon-delimited format: [days:]HH:MM:SS
        if (str_contains($uptime, ':')) {
            $parts = array_map('intval', explode(':', $uptime));
            if (count($parts) === 3) {
                return $parts[0] * 3600 + $parts[1] * 60 + $parts[2];
            }
            if (count($parts) === 4) {
                return $parts[0] * 86400 + $parts[1] * 3600 + $parts[2] * 60 + $parts[3];
            }
        }

        // Letter-suffix format: 1w2d3h4m5s
        $seconds = 0;
        $units = ['w' => 604800, 'd' => 86400, 'h' => 3600, 'm' => 60, 's' => 1];
        foreach ($units as $unit => $multiplier) {
            if (preg_match('/(\d+)' . $unit . '/i', $uptime, $matches)) {
                $seconds += (int) $matches[1] * $multiplier;
            }
        }

        return $seconds;
    }

    /**
     * Format rate limit for MikroTik
     */
    protected function formatRateLimit($package): string
    {
        $download = $package->bandwidth_download;
        $upload = $package->bandwidth_upload;

        if (!$download && !$upload) {
            return ''; // No rate limit = unlimited
        }

        // RouterOS hotspot user profile rate-limit format: rx/tx
        // Cast to int to avoid decimals like "4.00M" which RouterOS rejects
        $dl = $download ? (int) $download . 'M' : '0';
        $ul = $upload ? (int) $upload . 'M' : '0';

        return $ul . '/' . $dl;
    }

    /**
     * Parse data cap string (e.g., "1GB", "500MB") to bytes.
     * Returns null if no data cap or unparseable.
     */
    protected function parseDataCapToBytes(?string $dataCap): ?int
    {
        if (!$dataCap) {
            return null;
        }

        $dataCap = strtoupper(trim($dataCap));

        if (preg_match('/(\d+(?:\.\d+)?)\s*(GB|MB|KB)/', $dataCap, $matches)) {
            $value = floatval($matches[1]);
            $unit = $matches[2];

            switch ($unit) {
                case 'GB':
                    return (int) ($value * 1024 * 1024 * 1024);
                case 'MB':
                    return (int) ($value * 1024 * 1024);
                case 'KB':
                    return (int) ($value * 1024);
            }
        }

        return null;
    }

    /**
     * Format session timeout for MikroTik profile (HH:MM:SS)
     */
    protected function formatSessionTimeout($package): string
    {
        $seconds = $package->getSessionTimeoutSeconds();

        if ($seconds === null) {
            $seconds = 86400; // Default 24 hours
        }

        $hours = floor($seconds / 3600);
        $minutes = floor(($seconds % 3600) / 60);
        $remainingSeconds = $seconds % 60;

        return sprintf('%02d:%02d:%02d', $hours, $minutes, $remainingSeconds);
    }

    /**
     * Format limit-uptime for MikroTik user (e.g. "1d", "2h", "1w", "4w2d").
     * This is a user-level usage limit, distinct from the profile-level session-timeout.
     */
    protected function formatLimitUptime($package): string
    {
        $seconds = $package->getSessionTimeoutSeconds();

        if ($seconds === null) {
            return '';
        }

        $weeks = floor($seconds / 604800);
        $seconds %= 604800;
        $days = floor($seconds / 86400);
        $seconds %= 86400;
        $hours = floor($seconds / 3600);
        $seconds %= 3600;
        $minutes = floor($seconds / 60);

        $parts = [];
        if ($weeks > 0) $parts[] = $weeks . 'w';
        if ($days > 0) $parts[] = $days . 'd';
        if ($hours > 0) $parts[] = $hours . 'h';
        if ($minutes > 0) $parts[] = $minutes . 'm';

        return implode('', $parts) ?: '1d';
    }

    /**
     * Generate random password
     */
    protected function generatePassword(): string
    {
        return bin2hex(random_bytes(8)); // 16 character hex password
    }


