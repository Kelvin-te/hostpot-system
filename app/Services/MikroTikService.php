    /**
     * Sync database sessions with router active sessions
     * - Creates missing sessions on router
     * - Marks sessions as expired if they don't exist on router anymore
     */
    public function syncSessionsWithRouter(Router $router): array
    {
        try {
            $client = $this->connectToRouter($router);
            
            if (!$client) {
                return [
                    'success' => false,
                    'message' => 'Cannot connect to router',
                    'synced' => 0,
                    'created' => 0,
                    'expired' => 0,
                ];
            }

            // Get all active sessions from router (includes byte counters)
            $query = new Query('/ip/hotspot/active/print');
            $routerSessions = $client->query($query)->read();

            // Get all hotspot users from router
            $userQuery = new Query('/ip/hotspot/user/print');
            $routerUsers = $client->query($userQuery)->read();

            // Create maps of router sessions (with data) and users
            $routerSessionMap = [];  // username => session data
            foreach ($routerSessions as $rs) {
                $user = $rs['user'] ?? null;
                $mac = strtolower($rs['mac-address'] ?? '');

                if ($user) {
                    $routerSessionMap[$user] = $rs;
                }
                if ($mac) {
                    $routerSessionMap[$mac] = $rs;
                }
            }

            $routerUserMap = [];
            foreach ($routerUsers as $ru) {
                $user = $ru['name'] ?? null;
                if ($user) {
                    $routerUserMap[$user] = true;
                }
            }

            // Get all active sessions from database for this router
            $dbSessions = HotspotSession::active()
                ->whereHas('package', function($q) use ($router) {
                    $q->where('router_id', $router->id);
                })
                ->get();

            $syncedCount = 0;
            $createdCount = 0;
            $expiredCount = 0;

            $missingCount = 0;

            foreach ($dbSessions as $session) {
                $username = $session->mikrotik_username ?: $session->username ?: $session->session_id;
                $mac = strtolower($session->mac_address ?: '');

                // Check if session exists on router (currently active)
                $routerSession = $routerSessionMap[$username] ?? ($mac ? ($routerSessionMap[$mac] ?? null) : null);
                $existsOnRouter = $routerSession !== null;

                // Check if user exists on router (even if not active)
                $userExistsOnRouter = isset($routerUserMap[$username]);

                if (!$userExistsOnRouter) {
                    // User missing on router — re-create via API (idempotent)
                    $missingCount++;
                    $recreated = $this->createHotspotSession($session);

                    Log::info('Session user missing on router, re-created via API', [
                        'session_id' => $session->session_id,
                        'username' => $username,
                        'recreated' => $recreated,
                    ]);
                } elseif ($existsOnRouter) {
                    // Session is active on router — update byte counters
                    $syncedCount++;

                    $uploadBytes = (int) ($routerSession['bytes-in'] ?? 0);
                    $downloadBytes = (int) ($routerSession['bytes-out'] ?? 0);
                    $uptime = $routerSession['uptime'] ?? null;

                    $updateData = [
                        'bytes_uploaded' => $uploadBytes,
                        'bytes_downloaded' => $downloadBytes,
                        'bytes_total' => $uploadBytes + $downloadBytes,
                    ];

                    if ($uptime) {
                        $data = $session->mikrotik_data ?? [];
                        $data['uptime_seconds'] = $this->parseUptimeToSeconds($uptime);
                        $data['last_synced_at'] = now()->toIso8601String();
                        $updateData['mikrotik_data'] = $data;
                    }

                    $session->update($updateData);
                } else {
                    // Session is NOT active on router — the user was
                    // disconnected by MikroTik (timeout, data limit, logout,
                    // admin kick, etc.) but our DB still shows it as active.
                    // Mark as 'disconnected' if time remains (user can
                    // reconnect), or 'expired' if time has run out.
                    //
                    // BUT: if the user has never connected (no bytes, no
                    // uptime), they may simply not have logged in through
                    // the captive portal yet. Don't expire them — the
                    // hotspot user still exists on the router and will
                    // work once they do log in.
                    $hasUsedData = ($session->bytes_total ?? 0) > 0
                        || !empty($session->mikrotik_data['uptime_seconds']);

                    if (!$hasUsedData) {
                        // User hasn't logged in yet — skip, don't expire
                        continue;
                    }

                    $stillValid = $session->expires_at && $session->expires_at > now();

                    $session->update([
                        'status' => $stillValid ? 'disconnected' : 'expired',
                        'expires_at' => $stillValid ? $session->expires_at : now(),
                    ]);

                    $expiredCount++;

                    Log::info('Sync: ' . ($stillValid ? 'disconnected' : 'expired') . ' stale session (not active on router)', [
                        'session_id' => $session->session_id,
                        'username' => $username,
                        'router_id' => $router->id,
                    ]);
                }
            }

            return [
                'success' => true,
                'message' => "Synced $syncedCount sessions, $missingCount re-created, $expiredCount expired",
                'synced' => $syncedCount,
                'created' => $createdCount,
                'missing' => $missingCount,
                'expired' => $expiredCount,
            ];
            
        } catch (Exception $e) {
            Log::error('Failed to sync sessions with router', [
                'router_id' => $router->id,
                'error' => $e->getMessage()
            ]);
            
            return [
                'success' => false,
                'message' => 'Sync failed: ' . $e->getMessage(),
                'synced' => 0,
                'created' => 0,
                'expired' => 0,
            ];
        }
    }

    /**
     * Check whether a specific HotspotSession is still active on the router.
     * Used by getActiveSession() for on-demand verification.
     *
     * Returns true if the session is found in /ip/hotspot/active/print
     * (matched by username or MAC). Returns false if not found or on error.
     */
    public function isSessionActiveOnRouter(HotspotSession $session): bool
    {
        try {
            $router = $session->package?->router;

            if (!$router) {
                return false;
            }

            $client = $this->connectToRouter($router);

            if (!$client) {
                // Can't reach router — assume session is still active to
                // avoid falsely expiring sessions during network issues.
                return true;
            }

            $username = $session->mikrotik_username ?: $session->username ?: $session->session_id;
            $mac = strtolower($session->mac_address ?: '');

            // Filter by username — avoids fetching all active sessions on busy routers
            $query = (new Query('/ip/hotspot/active/print'))
                ->where('user', $username);
            $activeSessions = $client->query($query)->read();

            foreach ($activeSessions as $active) {
                $activeUser = $active['user'] ?? null;
                $activeMac = strtolower($active['mac-address'] ?? '');

                if ($activeUser && $activeUser === $username) {
                    return true;
                }
                if ($mac && $activeMac === $mac) {
                    return true;
                }
            }

            return false;

        } catch (Exception $e) {
            Log::warning('isSessionActiveOnRouter: error, assuming active', [
                'session_id' => $session->session_id,
                'error' => $e->getMessage(),
            ]);

            // On error, assume active to avoid false expiry
            return true;
        }
    }

    /**
     * Resolve the HotSpot gateway/server IP from already-fetched RouterOS
     * entries. This is the address MikroTik uses to build the `link-login`
     * URL when the HotSpot profile's dns-name is empty - it is intentionally
     * distinct from the router's management/API/WireGuard IP.
     *
     * Preference order:
     * 1. The HotSpot profile's `hotspot-address` property (explicit override).
     * 2. The IP address bound to the HotSpot's own interface.
     *
     * @param array|null $profileEntry Row from /ip/hotspot/profile/print for the hotspot's profile.
     * @param array|null $interfaceAddressEntry Row from /ip/address/print for the hotspot's interface.
     */
    public function resolveHotspotServerIp(?array $profileEntry, ?array $interfaceAddressEntry): ?string
    {
        $hotspotAddress = $profileEntry['hotspot-address'] ?? null;
        if (!empty($hotspotAddress)) {
            return explode('/', $hotspotAddress)[0];
        }

        $interfaceAddress = $interfaceAddressEntry['address'] ?? null;
        if (!empty($interfaceAddress)) {
            return explode('/', $interfaceAddress)[0];
        }

        return null;
    }

    /**
     * Test if hotspot service is enabled on router
     */
    public function testHotspotService(Router $router): array
    {
        try {
            $client = $this->connectToRouter($router);
            
            if (!$client) {
                return [
                    'success' => false,
                    'enabled' => false,
                    'message' => 'Cannot connect to router',
                    'interface' => null,
                    'server_ip' => null,
                ];
            }

            // Check if hotspot service is running
            $query = new Query('/ip/hotspot/print');
            $hotspotInfo = $client->query($query)->read();
            
            if (empty($hotspotInfo)) {
                return [
                    'success' => true,
                    'enabled' => false,
                    'message' => 'Hotspot service is not configured',
                    'interface' => null,
                    'server_ip' => null,
                ];
            }

            $hotspot = $hotspotInfo[0];
            $interface = $hotspot['interface'] ?? null;
            $profileName = $hotspot['profile'] ?? null;

            $profileEntry = null;
            if ($profileName) {
                $profileQuery = (new Query('/ip/hotspot/profile/print'))
                    ->where('name', $profileName);
                $profiles = $client->query($profileQuery)->read();
                $profileEntry = $profiles[0] ?? null;
            }

            $interfaceAddressEntry = null;
            if ($interface) {
                $addressQuery = (new Query('/ip/address/print'))
                    ->where('interface', $interface);
                $addresses = $client->query($addressQuery)->read();
                $interfaceAddressEntry = $addresses[0] ?? null;
            }

            $serverIp = $this->resolveHotspotServerIp($profileEntry, $interfaceAddressEntry ?: null);

            // RouterOS reports `hotspot-address=0.0.0.0` when the profile has no
            // explicit address configured. 0.0.0.0 can never be used to build
            // captive-portal handoff (link-login) URLs, so treat it as "not
            // detected" and warn the admin to configure the hotspot profile
            // with the router's LAN gateway IP.
            $serverIpWarning = null;
            if ($serverIp === null || $serverIp === '0.0.0.0') {
                $serverIp = null;
                $serverIpWarning = 'The hotspot profile has no valid hotspot-address configured. '
                    . 'Set it to the router\'s LAN gateway IP (the address clients reach the hotspot on), '
                    . 'as it is used to build captive-portal handoff links.';
            }

            return [
                'success' => true,
                'enabled' => true,
                'message' => 'Hotspot service is enabled',
                'interface' => $interface,
                'server_ip' => $serverIp,
                'server_ip_warning' => $serverIpWarning,
            ];
            
        } catch (Exception $e) {
            Log::error('Failed to test hotspot service', [
                'router_id' => $router->id,
                'error' => $e->getMessage()
            ]);
            
            return [
                'success' => false,
                'enabled' => false,
                'message' => 'Error checking hotspot service: ' . $e->getMessage(),
                'interface' => null,
                'server_ip' => null,
            ];
        }
    }

