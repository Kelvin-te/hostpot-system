    /**
     * Recursively upload files from a local directory to the router.
     * Text files (html, css, js, txt, json) get placeholder substitution.
     * Binary files (ico, png, woff2) are skipped — they must be uploaded manually via FTP/WinBox.
     */
    private function uploadDirectoryFiles(Client $client, string $sourceDir, string $remotePath, array $replacements, int &$uploaded, array &$errors): void
    {
        foreach (scandir($sourceDir) as $item) {
            if ($item === '.' || $item === '..') {
                continue;
            }

            $sourcePath = $sourceDir . DIRECTORY_SEPARATOR . $item;
            $remoteFilePath = $remotePath . '/' . $item;

            if (is_dir($sourcePath)) {
                $this->uploadDirectoryFiles($client, $sourcePath, $remoteFilePath, $replacements, $uploaded, $errors);
                continue;
            }

            $extension = strtolower(pathinfo($item, PATHINFO_EXTENSION));

            // Only upload text files via API; binary files need FTP/WinBox
            if (!in_array($extension, ['html', 'css', 'js', 'txt', 'json'], true)) {
                continue;
            }

            $contents = file_get_contents($sourcePath);
            $contents = strtr($contents, $replacements);

            try {
                // Check if file already exists
                $printQuery = new Query('/file/print');
                $printQuery->where('name', $remoteFilePath);
                $existing = $client->query($printQuery)->read();

                if (!empty($existing)) {
                    // Update existing file
                    $setQuery = new Query('/file/set');
                    $setQuery->equal('.id', $existing[0]['.id']);
                    $setQuery->equal('contents', $contents);
                    $client->query($setQuery)->read();
                } else {
                    // Create new file
                    $addQuery = new Query('/file/add');
                    $addQuery->equal('name', $remoteFilePath);
                    $addQuery->equal('contents', $contents);
                    $client->query($addQuery)->read();
                }

                $uploaded++;
            } catch (Exception $e) {
                $errors[] = $remoteFilePath . ': ' . $e->getMessage();
                Log::warning('Failed to upload file to router', [
                    'file' => $remoteFilePath,
                    'error' => $e->getMessage(),
                ]);
            }
        }
    }
